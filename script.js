const menuToggle = document.querySelector(".menu-toggle");
const navLinks = document.querySelector(".nav-links");
const year = document.querySelector("#year");
const languageButtons = document.querySelectorAll("[data-lang-option]");

function setLanguage(language) {
  const selectedLanguage = translations[language] ? language : "ar";
  const isArabic = selectedLanguage === "ar";

  document.documentElement.lang = selectedLanguage;
  document.documentElement.dir = isArabic ? "rtl" : "ltr";
  document.body.dataset.lang = selectedLanguage;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const text = translations[selectedLanguage][element.dataset.i18n];
    if (text) element.textContent = text;
  });

  document.querySelector('meta[name="description"]').content =
    translations[selectedLanguage]["meta.description"];
  document.title = isArabic ? "Baj_Antix | موقعنا" : "Baj_Antix | Digital solutions";
  document.querySelector(".nav-links").setAttribute(
    "aria-label",
    isArabic ? "القائمة الرئيسية" : "Main navigation"
  );
  document.querySelector(".lang-switch").setAttribute(
    "aria-label",
    isArabic ? "اختيار اللغة" : "Choose language"
  );
  if (menuToggle) {
    const isExpanded = menuToggle.getAttribute("aria-expanded") === "true";
    menuToggle.setAttribute(
      "aria-label",
      isArabic
        ? isExpanded ? "إغلاق القائمة" : "فتح القائمة"
        : isExpanded ? "Close menu" : "Open menu"
    );
  }

  languageButtons.forEach((button) => {
    const isActive = button.dataset.langOption === selectedLanguage;
    button.classList.toggle("active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  if (year) year.textContent = new Date().getFullYear();
  try {
    localStorage.setItem("baj-antix-language", selectedLanguage);
  } catch {
    // Language switching still works when storage is unavailable.
  }
}

function closeMenu() {
  if (!menuToggle || !navLinks) return;
  navLinks.classList.remove("open");
  menuToggle.setAttribute("aria-expanded", "false");
  menuToggle.setAttribute(
    "aria-label",
    document.documentElement.lang === "ar" ? "فتح القائمة" : "Open menu"
  );
}

if (menuToggle && navLinks) {
  menuToggle.addEventListener("click", () => {
    const isExpanded = menuToggle.getAttribute("aria-expanded") === "true";
    menuToggle.setAttribute("aria-expanded", String(!isExpanded));
    menuToggle.setAttribute(
      "aria-label",
      isExpanded
        ? document.documentElement.lang === "ar" ? "فتح القائمة" : "Open menu"
        : document.documentElement.lang === "ar" ? "إغلاق القائمة" : "Close menu"
    );
    navLinks.classList.toggle("open", !isExpanded);
  });

  navLinks.addEventListener("click", (event) => {
    if (event.target.closest("a")) closeMenu();
  });

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") closeMenu();
  });
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.langOption));
});

let savedLanguage = "ar";
try {
  savedLanguage = localStorage.getItem("baj-antix-language") || "ar";
} catch {
  savedLanguage = "ar";
}
setLanguage(savedLanguage);
